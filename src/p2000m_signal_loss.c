uint8_t p2000m_signal_loss_glyph_row(char character, unsigned row) {
    if (row >= P2000M_SIGNAL_LOSS_GLYPH_HEIGHT) {
        return 0u;
    }
    if (character >= 'a' && character <= 'z') {
        character = (char)(character - 'a' + 'A');
    }
    if (character >= 'A' && character <= 'Z') {
        return signal_lost_font[(unsigned)(character - 'A')][row];
    }
    if (character >= '0' && character <= '9') {
        return signal_lost_font[26u + (unsigned)(character - '0')][row];
    }
    if (character == '.') {
        return row == 6u ? 0x04u : 0x00u;
    }
    if (character == '+') {
        static const uint8_t plus[P2000M_SIGNAL_LOSS_GLYPH_HEIGHT] = {
            0x00u, 0x04u, 0x04u, 0x1fu, 0x04u, 0x04u, 0x00u,
        };
        return plus[row];
    }
    if (character == '-') {
        return row == 3u ? 0x1fu : 0x00u;
    }
    return 0u;
}
